# The template conf.py written into each per-project scratch dir.
# `{exclude_patterns_repr}` and `{extensions_repr}` are python-literal
# lists already formatted by write_conf_py.
_CONF_PY_TEMPLATE = '''"""Auto-generated by docstrap for the markdown layout.

Do not edit; docstrap regenerates this per build."""
project = {project!r}

# The scanned project's slug, carried through the build so the tools can
# address the project by the name its draft root actually has.
# `project` above is a human-readable title and is not that name.
docstrap_project_slug = {project_slug!r}

# The mount of the project's draft source, under which the answer store
# is read and kept to what was decided — None when it has none.
docstrap_draft_mount = {draft_mount!r}

# Where the file index lives. `docstrap.sphinx.composed` reads a
# section's contents from it instead of walking the tree, so a page is
# recomputed from a query rather than cached as a file anywhere.
docstrap_index_db = {index_db!r}

# A note the project's landing page carries about its own state — an
# undeclared docs_root, say. Passed rather than written into a document,
# because a build writes no document.
docstrap_root_note = {root_note!r}

# The model a store's aggregate page is composed from. Empty for a
# project build; `docstrap.build` fills it for the pages that list
# builds, which are the one thing the file index cannot know.
docstrap_aggregate = {aggregate!r}

# Where this build's output sits below the site root the viewer shell is
# published at, as `store/project/` or '' — None when no shell is
# published above it. Each page composes its way into the viewer from it.
docstrap_viewer_base = {viewer_base!r}

extensions = {extensions_repr}
source_suffix = {{
    ".md": "markdown",
    ".rst": "restructuredtext",
    {section_suffix!r}: {section_filetype!r},
    {aggregate_suffix!r}: {aggregate_filetype!r},
}}
master_doc = "index"
exclude_patterns = {exclude_patterns_repr}

myst_enable_extensions = [
    "colon_fence",
    "deflist",
    "fieldlist",
    "tasklist",
    "linkify",
    "smartquotes",
    "substitution",
    "attrs_inline",
    "attrs_block",
]
myst_heading_anchors = 4

# Route ```mermaid fenced code blocks through the sphinxcontrib.mermaid
# directive (so they render as interactive diagrams, not literal code).
myst_fence_as_directive = ["mermaid"]

html_theme = "furo"
html_title = {project!r}

# Suppress the built-in "view page source" affordance and the _sources
# copy of raw markdown so raw source isn't published.
html_copy_source = False
html_show_sourcelink = False
'''


def _write_generated(path: Path, text: str, build_root: Path) -> None:
    """Write a file the build generated, refusing to leave the build area.

    The one invariant of this module, made executable: a generated file
    lands inside ``build_root`` or it does not land. The check is on the
    *realpath of the parent directory*, because that is what a symlink
    defeats — the path itself looks innocent right up until the write
    goes through it into somebody's repository.

    Nothing should ever raise this. It is here so that if some later
    change reintroduces a symlinked directory in the scratch tree, the
    build fails loudly instead of quietly committing files to a project.
    """
    parent = os.path.realpath(path.parent)
    root = os.path.realpath(build_root)
    if parent != root and not parent.startswith(root + os.sep):
        raise LayoutError(
            f"refusing to write a generated file outside the build: {path} "
            f"resolves to {parent}, which is not under {root}. A docstrap "
            f"build reads a project; it never writes into one."
        )
    path.write_text(text, encoding="utf-8")


def write_marker(scratch_dir: Path, relative: Path | str) -> Path:
    """Create a composed page's zero-byte marker inside a build.

    The marker is how a page with no source becomes a Sphinx document:
    ``source_suffix`` maps its suffix to a docstrap parser that composes
    the page and ignores the (empty) file. See
    :mod:`docstrap.sphinx.composed` for why this rather than markdown,
    and for the alternatives that were rejected.

    Public because :mod:`docstrap.build` composes the aggregate pages the
    same way, and the guard in :func:`_write_generated` is the one that
    has to run for every generated write in a docstrap build.
    """
    path = scratch_dir / relative
    _write_generated(path, "", scratch_dir)
    return path


def _build_exclude_patterns(exclude_dirs: tuple[str, ...]) -> list[str]:
    """Sphinx exclude_patterns for docstrap's exclude_dirs.

    Adds patterns so excluded directory names are pruned at any depth.
    """
    base = ["_build", ".DS_Store", "Thumbs.db"]
    for name in exclude_dirs:
        base.append(name)
        base.append(f"**/{name}")
        base.append(f"{name}/**")
        base.append(f"**/{name}/**")
    return base


# Extensions the layout itself needs, regardless of what tools exist.
# `docstrap.sphinx.composed` is one of them and not an optional extra:
# without it the section markers have no parser and the site has no
# sidebar. `docstrap.sphinx.answer_drafts` is not optional either:
# without it a draft source publishes the answer store's drafts, which
# are kept from every audience.
_LAYOUT_EXTENSIONS = (
    "myst_parser",
    "sphinxcontrib.mermaid",
    "docstrap.sphinx.composed",
    "docstrap.sphinx.answer_drafts",
)


def conf_extensions() -> list[str]:
    """The generated ``extensions`` list: the layout's, then the tools'.

    The tool half comes from the declarations, so a new tool directory
    reaches the built site without this template being edited. Nothing
    here names a tool.
    """
    return list(_LAYOUT_EXTENSIONS) + list(registry.sphinx_extensions())


def write_conf_py(
    scratch_dir: Path,
    project_name: str,
    exclude_dirs: tuple[str, ...] = (),
    project_slug: str = "",
    index_db: Path | str = "",
    root_note: str = "",
    aggregate: dict | None = None,
    viewer_base: str | None = None,
    draft_mount: str | None = None,
) -> None:
    """Write the bundled Sphinx conf.py into scratch_dir.

    Public helper — build.py's aggregate builders reuse this so every
    Sphinx pass in a docstrap run shares the same theme and MyST config.

    ``project_slug`` is the scanned project's slug. An aggregate page
    belongs to no project and passes none; a project build always passes
    its own, because a tool that addressed the project by its title
    would write into a directory the project does not link to.

    ``index_db``, ``root_note`` and ``aggregate`` are how a composed page
    learns what it is composed of. They are conf.py values rather than
    files because conf.py is already the one generated thing a build
    writes, and a second one would be a cache of the page in some other
    format — which is the thing this design removed.

    ``viewer_base`` is where the output lands below the site the viewer
    shell is published at (:func:`docstrap.viewer.manifest.site_base`),
    or None when there is none; it is what gives every page its button
    into the viewer.

    ``draft_mount`` is the mount of the project's draft source, read by
    :mod:`docstrap.sphinx.answer_drafts`; None when the build has none.
    """
    _write_generated(
        scratch_dir / "conf.py",
        _CONF_PY_TEMPLATE.format(
            project=project_name,
            project_slug=project_slug,
            draft_mount=draft_mount,
            index_db=str(index_db),
            root_note=root_note,
            aggregate=aggregate,
            viewer_base=viewer_base,
            section_suffix=composed.MARKER_SUFFIX,
            section_filetype=composed.SECTION_FILETYPE,
            aggregate_suffix=composed.AGGREGATE_MARKER_SUFFIX,
            aggregate_filetype=composed.AGGREGATE_FILETYPE,
            exclude_patterns_repr=repr(_build_exclude_patterns(exclude_dirs)),
            extensions_repr=repr(conf_extensions()),
        ),
        scratch_dir,
    )


# An `index.md` in a documentation tree is not allowed to be there, so
# the mirror does not bring one into the build and no directory is
# excused a composed page for holding one. Owned by
# `docstrap.sectionindex`; re-exported under the name this module uses.
_REFUSED_INDEX_FILES = sectionindex.REFUSED_INDEX_FILES


# The docname a README takes in the scratch dir. It is one more document
# in the project's set, so it needs a name of its own — and one nothing
# already inside docs_dir has claimed.
_README_DOCNAME = "readme"
_README_FALLBACK_DOCNAME = "project-readme"


def _readme_docname(scratch_dir: Path) -> str:
    """A docname for the README that no scratch_dir entry has taken.

    Compared case-insensitively, so the answer also holds on filesystems
    that do not distinguish `README.md` from `readme.md`.
    """
    taken = {p.stem.lower() for p in scratch_dir.iterdir()}
    for candidate in (_README_DOCNAME, _README_FALLBACK_DOCNAME):
        if candidate not in taken:
            return candidate
    n = 2
    while f"{_README_FALLBACK_DOCNAME}-{n}" in taken:
        n += 1
    return f"{_README_FALLBACK_DOCNAME}-{n}"


def _literal_fence(text: str) -> str:
    """A backtick fence longer than any run of backticks inside text."""
    longest = run = 0
    for ch in text:
        run = run + 1 if ch == "`" else 0
        longest = max(longest, run)
    return "`" * max(3, longest + 1)


def _attach_readme(
    scratch_dir: Path,
    project: ScannedProject,
    sources: dict[str, str] | None = None,
) -> None:
    """Bring the project's README into scratch as one further document.

    That one file and nothing else: a `.md` README is symlinked on its
    own, never by exposing its parent, so the rest of the project root
    stays out of the build.

    A `.txt` README is not markdown, and the generated conf.py maps only
    `.md`/`.rst` to a parser. Rather than teach Sphinx that every `.txt`
    in a docs tree is prose, docstrap wraps this one: a generated `.md`
    page holding the text verbatim in a literal block. Plain text is
    published as written instead of being reinterpreted as markup.
    """
    readme = project.readme_path
    if readme is None or not readme.is_file():
        return

    target = scratch_dir / f"{_readme_docname(scratch_dir)}.md"
    if readme.suffix.lower() == ".md":
        target.symlink_to(readme.resolve())
        return

    try:
        text = readme.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return
    fence = _literal_fence(text)
    _write_generated(
        target,
        f"# {project.title} README\n\n{fence}text\n{text.rstrip()}\n{fence}\n",
        scratch_dir,
    )
    if sources is not None:
        # The wrapper is the document Sphinx reads, but the *file* is the
        # project's README. The index records where bytes are, and these
        # bytes are not in the build that is about to be deleted.
        sources[str(target)] = str(readme.resolve())


def _mirror_tree(
    source: Path,
    destination: Path,
    exclude_dirs: set[str],
    skip_names: frozenset[str] = frozenset(),
    sources: dict[str, str] | None = None,
    refused: list[Path] | None = None,
    skip_paths: frozenset[str] = frozenset(),
    _ancestors: tuple[str, ...] = (),
) -> None:
    """Shadow ``source`` inside ``destination``: real dirs, linked files.

    Every directory becomes a directory the build made; every file
    becomes a symlink to the real document. Sphinx reads the same bytes
    it read when the whole tree was one symlink, and the docnames are
    unchanged — but there is no longer a symlinked directory anywhere in
    the build, so there is nothing for a composed page to be written
    *through*.

    A directory the site does not publish — dotted, underscored,
    excluded, vendored — is linked rather than mirrored. Nothing is
    composed inside it and nothing descends into it, so linking costs a
    walk and preserves what was on disk before.

    Cycles terminate because a directory resolving to one of its own
    ancestors is linked rather than descended. That test is the ancestor
    chain and not every directory seen so far, deliberately: two siblings
    pointing at the same target are not a cycle, and mirroring only the
    first would leave the second's section page in a toctree with nothing
    behind it.

    ``sources`` collects ``{mirrored directory: the real directory behind
    it}``. A mirrored directory is a directory the *build* made, so its
    own realpath is a build path — and the index is a record of where
    documents are, not of where a build put a shadow of them. Only this
    walk knows the answer, so only this walk can record it.

    ``refused`` collects the `index.md` files found on the way. One is
    not linked into the build, so it is not published and cannot shadow
    the page docstrap composes for its directory — a docs tree is not
    allowed to hold one at all. It is **not** deleted and not touched:
    this walk reads a project and writes nothing into one. The build
    reports what it collected here, because the way this went wrong the
    first time was silently.

    ``skip_names`` applies at the top of ``source`` only; ``skip_paths``
    is real paths skipped at any depth — another declared source lying
    inside this one, which is mirrored at its own mount instead.
    """
    here = os.path.realpath(source)
    ancestors = _ancestors + (here,)
    if sources is not None:
        sources.setdefault(str(destination), here)

    try:
        entries = sorted(source.iterdir())
    except OSError:
        return

    for entry in entries:
        if entry.name in skip_names:
            continue
        if skip_paths and os.path.realpath(entry) in skip_paths:
            continue
        if entry.name in _REFUSED_INDEX_FILES and not entry.is_dir():
            if refused is not None:
                refused.append(entry)
            continue
        target = destination / entry.name
        if target.exists() or target.is_symlink():
            continue
        if entry.is_dir():
            if (
                not sectionindex.is_section_dir(entry.name, exclude_dirs)
                or os.path.realpath(entry) in ancestors
            ):
                target.symlink_to(entry.resolve())
                continue
            target.mkdir()
            _mirror_tree(
                entry,
                target,
                exclude_dirs,
                sources=sources,
                refused=refused,
                skip_paths=skip_paths,
                _ancestors=ancestors,
            )
        else:
            target.symlink_to(entry.resolve())


class _Mounts:
    """Where each source sits in scratch, and what that decides.

    A source mounted below the scratch root is not a section: nothing
    lists the mount itself and no page is composed for it, nor for a
    directory that exists only to hold a deeper mount. What a mount holds
    is listed on the project's landing page, in its role's group, so a
    draft mount's `notes` is a sibling of `specs` in the sidebar rather
    than buried a level down.
    """

    def __init__(self, sources: tuple[ResolvedSource, ...], root_role: str):
        self.roles = {s.mount: s.role for s in sources if s.mount}
        self.root_role = root_role
        self.hidden: set[str] = set()
        for mount in self.roles:
            parts = mount.split("/")
            for depth in range(1, len(parts) + 1):
                self.hidden.add("/".join(parts[:depth]))

    def is_section(self, relative: str) -> bool:
        return relative not in self.hidden

    def parent_docname(self, relative_dir: str) -> str:
        """The section page that lists what is directly inside ``relative_dir``.

        ``''`` is the scratch root, whose page is the project's landing
        page, and so is every mount and every directory above one.
        """
        if relative_dir in ("", ".") or relative_dir in self.hidden:
            return sectionindex.GENERATED_INDEX_NAME
        return f"{relative_dir}/{sectionindex.GENERATED_INDEX_NAME}"

    def grouping(self, relative: str) -> str:
        """The role of the source ``relative`` came from: its landing-page group."""
        best = ""
        for mount in self.roles:
            if (relative == mount or relative.startswith(mount + "/")) and len(mount) > len(best):
                best = mount
        return self.roles[best] if best else self.root_role


def _document_title(real_path: Path, data: bytes) -> str:
    """What the index calls a document.

    Resolved through :func:`docstrap.strapdance.read_title`, which is the
    title chain's own owner, from bytes already read for the hash. Never
    a second parser and never a second answer.
    """
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        text = data.decode("utf-8", errors="replace")
    try:
        return strapdance.read_title(real_path, text=text)
    except Exception:  # noqa: BLE001 — a title is never worth a failed build
        return sectionindex.humanize(real_path.stem)


def _index_tree(
    scratch_dir: Path,
    project: ScannedProject,
    sources: dict[str, str],
    mounts: _Mounts,
) -> list[fileindex.Entry]:
    """Index the mirrored tree: one entry per published directory and file.

    The build's one walk of what it is about to publish. Every question
    a section page asks afterwards is answered from the table this fills,
    which is what makes the pages recomputable without a second walk and
    a watcher able to keep them current one event at a time.

    The walk does not follow symlinks. Every directory in the mirrored
    tree is one the build made and every file in it is a link to a real
    document, so a link that is a *directory* is one the mirror declined
    to descend — excluded, hidden or a cycle — and this declines it too.

    Every ``path`` recorded is a path in the project, never in the build,
    and ``sources`` is what makes that true. A document that is a symlink
    resolves through itself to the project; a mirrored *directory*
    resolves to the build, and a `.txt` README's generated wrapper is a
    build file standing in for a project one. Both of the latter are in
    ``sources``, filled by the walks that know — :func:`_mirror_tree` and
    :func:`_attach_readme`.
    """
    exclude_dirs = set(project.exclude_dirs)
    exclude_suffixes = set(project.exclude_file_suffixes)
    document_ids = _known_document_ids()

    entries: list[fileindex.Entry] = [
        fileindex.Entry(
            project=project.slug,
            docname=sectionindex.GENERATED_INDEX_NAME,
            path=str((project.docs_dir or project.root_dir).resolve()),
            parent_docname="",
            kind=fileindex.SECTION,
            grouping=mounts.root_role,
            title=project.title,
            sort_key="",
        )
    ]

    for current, dirs, files in os.walk(str(scratch_dir), followlinks=False):
        here = Path(current)
        relative = "" if here == scratch_dir else str(
            here.relative_to(scratch_dir).as_posix()
        )
        dirs[:] = sorted(d for d in dirs if sectionindex.is_section_dir(d, exclude_dirs))

        for name in dirs:
            child_relative = f"{relative}/{name}" if relative else name
            if not mounts.is_section(child_relative):
                # A mount is not a section: nothing lists it and nothing
                # links a page for it. Its children are listed on the
                # landing page under their role's caption.
                continue
            entries.append(
                fileindex.Entry(
                    project=project.slug,
                    docname=f"{child_relative}/{sectionindex.GENERATED_INDEX_NAME}",
                    path=sources.get(
                        str(here / name), os.path.realpath(here / name)
                    ),
                    parent_docname=mounts.parent_docname(relative),
                    kind=fileindex.SECTION,
                    grouping=mounts.grouping(child_relative),
                    title=sectionindex.humanize(name),
                    sort_key=name,
                )
            )

        for name in sorted(files):
            if not sectionindex.is_document_file(name, exclude_suffixes):
                continue
            path = here / name
            real = Path(os.path.realpath(path))
            try:
                data = real.read_bytes()
            except OSError:
                continue
            stem = name.rsplit(".", 1)[0]
            docname = f"{relative}/{stem}" if relative else stem
            recorded = sources.get(str(path), str(real))
            entries.append(
                fileindex.Entry(
                    project=project.slug,
                    docname=docname,
                    path=recorded,
                    parent_docname=mounts.parent_docname(relative),
                    kind=fileindex.DOCUMENT,
                    grouping=mounts.grouping(relative),
                    title=_document_title(real, data),
                    sort_key=name,
                    content_hash=metadata.git_blob_hash(data),
                    document_id=document_ids.get(str(real)),
                )
            )

    return entries


def _known_document_ids() -> dict[str, str]:
    """Path-to-id for every document the metadata store knows, in one query.

    A rename then survives where renames already survive — `documents.
    current_path` and `path_history` — rather than in a second history
    kept by the index. A file nobody has tagged is absent here, and for
    that one the content hash is the identity; see
    :mod:`docstrap.fileindex`.
    """
    try:
        return metadata.ids_by_path()
    except Exception:  # noqa: BLE001 — the index is not worth a failed build
        return {}


def _write_section_markers(
    scratch_dir: Path, project: ScannedProject, mounts: _Mounts
) -> int:
    """Put a composed page's marker in every section, with no exception.

    Every section gets a zero-byte marker whose parser composes the page
    — see :mod:`docstrap.sphinx.composed`. There is no longer a check for
    a directory that carries its own `index.md`: the mirror does not
    bring one into the build, because a docs tree is not allowed to hold
    one. That check is what let the first build's output become permanent
    and go stale in place, and with nothing generated into a tree it had
    nothing left to protect.

    The walk does not follow symlinks. The mirrored tree has no symlinked
    directory to descend anyway; refusing to follow one is the second of
    the two rules keeping writes inside the build, and the one that still
    holds if the first is ever broken.
    """
    written = 0
    for directory in sectionindex.sites(
        scratch_dir, set(project.exclude_dirs), follow_symlinks=False
    ):
        if not mounts.is_section(directory.relative_to(scratch_dir).as_posix()):
            continue
        write_marker(scratch_dir, directory.relative_to(scratch_dir) / composed.MARKER_NAME)
        written += 1
    return written


def _draft_mount(
    contributed: tuple[ResolvedSource, ...], declared: tuple[ResolvedSource, ...]
) -> str | None:
    """The mount of the draft source the answer store is read under.

    A plugin's draft source first, then a declared one — the order
    :func:`docstrap.drafts.draft_root` asks in — and None when there is
    neither.
    """
    return next((s.mount for s in contributed + declared if s.is_draft), None)


def _root_role(project: ScannedProject) -> str:
    """The role of the source at the project root: the landing page's own group."""
    return next(
        (s.role for s in project.sources if s.mount == ""), fileindex.DOCS
    )


def _refused_note(refused: list[Path], docs_dir: Path) -> str:
    """What the landing page says about index files found in the tree.

    Reported rather than repaired, for the same reason a missing
    docs_root is: deleting somebody's file is a write into their
    project. Named individually, because the way this defect survived
    was that nothing ever said the files were there.
    """
    if not refused:
        return ""
    names = ", ".join(sorted(_relative_display(p, docs_dir) for p in refused))
    return (
        f"Not published: {names}. An index file in a documentation tree is not "
        f"allowed — docstrap composes every section page during the build and "
        f"writes none into a project. Delete it; nothing here will."
    )


def _relative_display(path: Path, docs_dir: Path) -> str:
    """``path`` as the docs tree names it, or in full when it is elsewhere."""
    try:
        return path.resolve().relative_to(docs_dir.resolve()).as_posix()
    except ValueError:
        return str(path)


def _root_note(
    project: ScannedProject,
    docs_dir_missing: bool,
    refused: list[Path] | None = None,
) -> str:
    """What the landing page says about the project's own state.

    Two things: a declared docs_root that is not there, and index files
    found inside one. Both are reported rather than repaired, because
    creating or deleting a file in the project is the thing a build does
    not do.
    """
    notes = []
    if not project.sources:
        notes.append(
            "No sources: nothing in the settings names a folder of this project "
            "to publish. State `sources` (or `docs_root`) in its `.docstrap` or "
            "the user config — docstrap has no built-in folder name."
        )
    elif docs_dir_missing:
        notes.append(
            f"No documentation directory yet: `{_docs_dir_display(project)}` does not "
            f"exist. Create it, add markdown, and rebuild — docstrap reads a project "
            f"and does not create directories in one."
        )
    refused_note = _refused_note(refused or [], project.docs_dir or project.root_dir)
    if refused_note:
        notes.append(refused_note)
    return " ".join(notes)


def _docs_dir_display(project: ScannedProject) -> str:
    """The project's docs_root written the way its `.docstrap` writes it."""
    if project.docs_dir is None:
        return "(no source mounted at the project root)"
    try:
        return project.docs_dir.resolve().relative_to(
            project.root_dir.resolve()
        ).as_posix()
    except ValueError:
        return str(project.docs_dir)


def build(
    project: ScannedProject, out_dir: Path, site_root: Path | None = None
) -> BuildResult:
    """Mirror the project into scratch, index it, sphinx-build.

    ``site_root`` is where the viewer shell is published, above
    ``out_dir``, or None when no shell is.

    The order matters and is the whole shape of the change that removed
    markdown from the build. Mirror, so there is a tree of real
    directories and linked documents; index it, so what each directory
    holds is a row in a table; write a marker into each section, so
    Sphinx asks docstrap for that page; build. Nothing between those
    steps produces a document, and the pages the site needs exist only
    as HTML at the end of it.

    A declared docs_root that does not exist is reported, on the landing
    page and in the result's notes, and nothing is created. An earlier
    version created the directory and left a placeholder document in it,
    which is the same defect as the composed section pages in a smaller
    form: a missing directory in someone's repository is not docstrap's
    to fill.
    """
    docs_dir_missing = project.docs_dir is None or not project.docs_dir.is_dir()

    # Each enabled plugin prepares the project before anything is
    # mirrored — wiring a draft area, say — and may then add sources after
    # the declared ones. Asked in that order, so a source a plugin's
    # preparation just made is one it can name. A source whose mount a
    # declared one already holds is not added.
    plugins.prepare_project(project)
    contributed = plugins.project_sources(project)
    sources = tuple(project.sources) + contributed
    mounts = _Mounts(sources, _root_role(project))

    scratch_dir = out_dir / "_scratch" / project.slug
    if scratch_dir.exists():
        shutil.rmtree(scratch_dir)
    scratch_dir.mkdir(parents=True, exist_ok=True)

    # Mirror each source into scratch at its mount: directories the build
    # makes, files symlinked to the real documents. An `index.md` is the
    # one file not brought across — a docs tree is not allowed to hold
    # one, so it is neither published nor read as that directory's
    # landing page. It is collected and reported, never touched.
    #
    # At the top of the root source, every mount's first step is skipped:
    # docstrap owns those slots and the sources behind them are mirrored
    # at them. `conf.py` is skipped because the
    # build writes its own into this directory a few lines down, and a
    # symlink there would be a write straight through into the project.
    # A declared source lying inside another is skipped by the outer
    # one's mirror at any depth, because it is mirrored at its own mount.
    exclude_dir_set = set(project.exclude_dirs)
    # Where each mirrored directory came from, so the index records the
    # project's paths and not the build's. Filled by the mirror, which is
    # the only walk that knows.
    mirrored_from: dict[str, str] = {}
    refused_indexes: list[Path] = []
    declared = frozenset(os.path.realpath(s.path) for s in sources)
    taken = frozenset(
        {"conf.py"} | {s.mount.split("/")[0] for s in sources if s.mount}
    )
    for source in sources:
        if not source.path.is_dir():
            continue
        skip_paths = declared - {os.path.realpath(source.path)}
        if not source.mount:
            _mirror_tree(
                source.path,
                scratch_dir,
                exclude_dir_set,
                skip_names=taken,
                sources=mirrored_from,
                refused=refused_indexes,
                skip_paths=skip_paths,
            )
            continue
        # A mount is made only when its source holds anything visible.
        # Mirrored like the root source, and for the same reason: a
        # composed page that persisted in a source would be read back as
        # a user's own landing page on the next build and never
        # refreshed. Nothing composes a page into anywhere now, but the
        # mirror is what makes that true by construction rather than by
        # remembering.
        try:
            content = [e for e in source.path.iterdir() if not e.name.startswith(".")]
        except OSError:
            content = []
        if not content:
            continue
        mount = scratch_dir / source.mount
        if mount.exists() or mount.is_symlink():
            continue
        mount.mkdir(parents=True)
        _mirror_tree(
            source.path,
            mount,
            exclude_dir_set,
            sources=mirrored_from,
            refused=refused_indexes,
            skip_paths=skip_paths,
        )

    # After both mirrors, so the landing page's note can name every index
    # file they refused, and before anything is read, so Sphinx has its
    # configuration. The project's own `conf.py` was kept out of the
    # mirror for this: the write below must land on a build file.
    index_db = paths.metadata_db_path()
    write_conf_py(
        scratch_dir,
        project.title,
        project.exclude_dirs,
        project.slug,
        index_db=index_db,
        root_note=_root_note(project, docs_dir_missing, refused_indexes),
        viewer_base=viewer.site_base(out_dir / project.slug, site_root),
        draft_mount=_draft_mount(contributed, project.sources),
    )

    # After every other scratch entry exists, so the README's docname is
    # chosen against the full set of names already in play.
    _attach_readme(scratch_dir, project, sources=mirrored_from)

    # Index what was mirrored, then mark the sections that need a page.
    # The index is reconciled rather than appended to: a document that
    # left the project since the last build leaves the table in the same
    # pass, so no stale row survives to be listed on a page.
    fileindex.reconcile(
        project.slug,
        _index_tree(scratch_dir, project, mirrored_from, mounts),
        index_db,
    )
    _write_section_markers(scratch_dir, project, mounts)
    # The project's landing page, composed like every other section page
    # and with no exception for a tree that wrote its own `index.md`.
    write_marker(scratch_dir, composed.MARKER_NAME)

    html_root = out_dir / project.slug
    html_root.mkdir(parents=True, exist_ok=True)

    result = subprocess.run(
        sphinx_build_command("-b", "html", "-q", str(scratch_dir), str(html_root)),
        capture_output=True,
        text=True,
    )
    warnings = (result.stderr or "").count("WARNING")
    if result.returncode != 0:
        raise LayoutError(
            f"sphinx-build failed for `{project.slug}` (exit {result.returncode}).\n"
            f"stderr:\n{result.stderr}"
        )
    notes = f"markdown layout via bundled config ({warnings} warnings)"
    if not project.sources:
        notes += "; no sources stated"
    elif docs_dir_missing:
        notes += f"; docs_root `{_docs_dir_display(project)}` does not exist"
    if refused_indexes:
        named = ", ".join(
            sorted(
                _relative_display(p, project.docs_dir or project.root_dir)
                for p in refused_indexes
            )
        )
        notes += (
            f"; {len(refused_indexes)} index file(s) in the docs tree not published "
            f"and not touched: {named}"
        )
    return BuildResult(
        project_slug=project.slug,
        html_root=html_root,
        warnings=warnings,
        notes=notes,
    )
