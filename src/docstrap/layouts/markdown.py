"""Markdown layout — docstrap's bundled MyST + Sphinx config.

For projects that just have loose Markdown files and no Sphinx setup
of their own. Docstrap writes a minimal conf.py into a per-build scratch
directory, mirrors the project's docs_dir into it, indexes what it found,
and invokes sphinx-build. The section pages the sidebar needs are
composed by :mod:`docstrap.sphinx.composed` from that index, as document
nodes, during the Sphinx run.

**A build produces no markdown.** Not in a project, not in the build, not
as a temporary file: the output is HTML, so the intermediate markdown
step this module used to have is not kept. What this module writes into
its scratch tree is a conf.py and, for each section, a zero-byte marker
that tells Sphinx to ask docstrap for that page.

**A build never writes into a project tree.** That is the older and
larger invariant this module is answerable for. Two
rules keep it, and either alone would be enough:

1. The scratch tree is *mirrored*, not symlinked whole — see
   :func:`_mirror_tree`. Every directory in it is one the build made;
   only leaf files are symlinks. A marker therefore lands in a directory
   the build owns.
2. Every generated write goes through :func:`_write_generated`, which
   refuses a destination outside the scratch directory.

The earlier arrangement symlinked each docs_dir entry and then walked
the scratch tree with ``followlinks=True``. A symlinked *directory* is a
hole through the build into the repository behind it, so the composed
section pages landed in five real repositories and were
committed there. The mirror closes the hole rather than stepping around
it.

A project publishes its **sources** — folders the one settings surface
names, each with a role and a mount. Each is mirrored
into scratch at its mount: the first at the scratch root, the others at
their own path unless they state one. A mount is not a section: what it
holds is listed on the project's landing page, in a group per role. A
plugin may add sources after the declared ones —
a draft area, say, role `draft` under a mount of its own, so drafts
appear in the site next to real docs under a listing of their own.

A project's README, which lives a level above docs_dir and so is not
reached by the mirrored tree, is brought in as one further document —
see _attach_readme. It joins the Docs listing alongside everything
docs_dir yields; it does not become or replace the landing page.

**An `index.md` in the docs tree is not brought into the build.** A
documentation tree holds no index.md at all, so one is not mirrored,
not indexed and not published, and no directory holding one is excused the page docstrap composes for it. It is left
exactly where it is — a build reads a project and writes nothing into
one — and named on the landing page and in the build result, because the
way this defect survived its first three months was that nothing said
the files were there.
"""
